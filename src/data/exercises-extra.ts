import type { Equipment, Exercise, LoadType, MuscleId } from '../types'

const EQ: Record<string, Equipment> = {
  S: 'sztanga', H: 'hantle', M: 'maszyna', W: 'wyciąg', C: 'masa ciała', K: 'kettlebell', I: 'inne', R: 'cardio',
}

/** Zapis jak w exercises.ts; ostatni argument – inne (potoczne) nazwy do wyszukiwania. */
function x(
  id: string, pl: string, en: string, eq: string, compound: 0 | 1, primary: string, secondary: string,
  inc: number, steps: string, tips: string, load?: LoadType, aliases?: string,
): Exercise {
  return {
    id, pl, en, equipment: EQ[eq], compound: compound === 1,
    load: load ?? (eq === 'R' ? 'cardio' : eq === 'C' ? 'bodyweight' : 'weight'),
    primary: primary.split(' ').filter(Boolean) as MuscleId[],
    secondary: secondary.split(' ').filter(Boolean) as MuscleId[],
    inc, steps: steps.split('|'), tips: tips.split('|'),
    aliases: aliases ? aliases.split('|') : undefined,
  }
}

